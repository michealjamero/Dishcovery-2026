    private void populateFields(String id) {
        String sql = "SELECT r_title, r_ingredients FROM Recipes WHERE r_id = ?";
        try (java.sql.Connection conn = con.connectDB();
             java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {
            pstmt.setString(1, id);
            try (java.sql.ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    String title = rs.getString("r_title");
                    Name.setText("Recipe: " + (title != null ? title : "Unknown"));
                    
                    String ingredients = rs.getString("r_ingredients");
                    if (ingredients != null && !ingredients.trim().isEmpty()) {
                        refreshIngredientTable(ingredients);
                    }
                }
            }
        } catch (java.sql.SQLException e) {
            System.out.println("Error populating fields: " + e.getMessage());
        }
    }

    private void refreshIngredientTable(String ingredients) {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
            new Object[][] {},
            new String[] {"Ingredient", "Quantity", "Unit"}
        ) {
            public boolean isCellEditable(int row, int column) { return false; }
        };
        ingredientsTable.setModel(model);
        
        if (ingredients == null || ingredients.trim().isEmpty()) return;
        
        String[] lines = ingredients.split("\\n");
        for (String line : lines) {
            if (line.trim().isEmpty()) continue;
            String namePart = line;
            String qtyPart = "";
            String unitPart = "";
            
            if (line.contains("(") && line.contains(")")) {
                namePart = line.substring(0, line.indexOf("(")).trim();
                String details = line.substring(line.indexOf("(") + 1, line.indexOf(")")).trim();
                String[] parts = details.split("\\s+");
                if (parts.length >= 1) qtyPart = parts[0];
                if (parts.length >= 2) unitPart = parts[1];
            }
            model.addRow(new Object[]{namePart, qtyPart, unitPart});
        }
    }

