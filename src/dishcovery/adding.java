    private void DONEActionPerformed(java.awt.event.ActionEvent evt) {
        if (recipeId == null) {
            JOptionPane.showMessageDialog(this, "No recipe selected to add ingredients to.");
            return;
        }

        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) ingredientsTable.getModel();
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < model.getRowCount(); i++) {
            String n = String.valueOf(model.getValueAt(i, 0));
            String q = String.valueOf(model.getValueAt(i, 1));
            String u = String.valueOf(model.getValueAt(i, 2));
            
            String line = n;
            if (!q.isEmpty() || !u.isEmpty()) {
                line += " (" + q + (u.isEmpty() ? "" : " " + u) + ")";
            }
            sb.append(line).append("\n");
        }

        try {
            con.updateRecord("UPDATE Recipes SET r_ingredients = ? WHERE r_id = ?", sb.toString().trim(), recipeId);
            JOptionPane.showMessageDialog(this, "Ingredients saved successfully!");
            new Manage().setVisible(true);
            this.dispose();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error saving ingredients: " + e.getMessage());
        }
    }

