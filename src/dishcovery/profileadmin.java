    private void openSelectedRecipe() {
        int row = sharedRecipeOFUser.getSelectedRow();
        if (row < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a recipe from the table to view.");
            return;
        }
        Object idObj = sharedRecipeOFUser.getValueAt(row, 0);
        if (idObj == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a valid recipe.");
            return;
        }

        View11.openFrom(this, String.valueOf(idObj), config.Session.getInstance().getUsername(), null);
    }

    private void loadProfile() {
        String identifier = config.Session.getInstance().getUsername();
        if (identifier == null || identifier.trim().isEmpty()) {
             return; 
        }
        config.config con = new config.config();
        con.ensureUsersTable();
        java.util.List<java.util.Map<String, Object>> rows = con.fetchRecords(
            "SELECT u_id, u_full_name, u_email, u_username, u_role, u_image FROM Users WHERE u_username = ? OR u_email = ? LIMIT 1",
            identifier, identifier
        );
        if (!rows.isEmpty()) {
            java.util.Map<String, Object> row = rows.get(0);
            try {
                Object idObj = row.get("u_id");
                if (idObj != null) {
                    currentUserId = Integer.parseInt(idObj.toString());
                }
            } catch (Exception ignore) {}
            String uname = String.valueOf(row.get("u_username"));
            String fname = String.valueOf(row.get("u_full_name"));
            String email = String.valueOf(row.get("u_email"));
            String role = String.valueOf(row.get("u_role"));
            jLabel3.setText(uname != null ? uname : "");
            profilename1.setText(fname != null ? fname : "");
            profileemail1.setText(email != null ? email : "");
            // profilerole is used for Following count, so we don't set it to role here

            Object imgObj = row.get("u_image");
            if (imgObj instanceof byte[]) {
                byte[] img = (byte[]) imgObj;
                if (img != null && img.length > 0) {
                    javax.swing.ImageIcon icon = new javax.swing.ImageIcon(img);
                    java.awt.Image im = icon.getImage();
                    java.awt.Image myImg = im.getScaledInstance(profile.getWidth(), profile.getHeight(), java.awt.Image.SCALE_SMOOTH);
                    profile.setIcon(new javax.swing.ImageIcon(myImg));
                }
            }

            con.ensureRecipesTable();
            double cnt = con.getSingleValue("SELECT COUNT(*) FROM Recipes WHERE r_author = ? AND r_status = 'Approve'", uname);
            NoRecipes.setText(String.valueOf((int) cnt));
        }
    }

