    private void EditProfile1ActionPerformed(java.awt.event.ActionEvent evt) {
        if (currentUserId == null) {
            int sid = config.Session.getInstance().getId();
            if (sid > 0) {
                currentUserId = sid;
            }
        }
        if (currentUserId == null) {
            String identifier = config.Session.getInstance().getUsername();
            if (identifier == null || identifier.trim().isEmpty()) {
                identifier = jLabel3.getText();
            }
            if (identifier == null || identifier.trim().isEmpty()) {
                identifier = profileemail1.getText();
            }
            if (identifier != null && !identifier.trim().isEmpty()) {
                config.config con = new config.config();
                con.ensureUsersTable();
                java.util.List<java.util.Map<String, Object>> rows = con.fetchRecords(
                    "SELECT u_id FROM Users WHERE u_username = ? OR u_email = ? LIMIT 1",
                    identifier, identifier
                );
                if (!rows.isEmpty()) {
                    try {
                        currentUserId = Integer.parseInt(String.valueOf(rows.get(0).get("u_id")));
                    } catch (Exception ignore) {}
                }
            }
        }
        if (currentUserId == null) {
            String name = profilename1.getText() != null ? profilename1.getText().trim() : "";
            String email = profileemail1.getText() != null ? profileemail1.getText().trim() : "";
            String uname = jLabel3.getText() != null ? jLabel3.getText().trim() : "";
            if ((!name.isEmpty() && !email.isEmpty()) || !uname.isEmpty()) {
                config.config con = new config.config();
                con.ensureUsersTable();
                java.util.List<java.util.Map<String, Object>> rows = con.fetchRecords(
                    "SELECT u_id FROM Users WHERE (u_full_name = ? AND u_email = ?) OR (u_username = ? OR u_email = ?) LIMIT 1",
                    name, email, uname, email
                );
                if (!rows.isEmpty()) {
                    try {
                        currentUserId = Integer.parseInt(String.valueOf(rows.get(0).get("u_id")));
                    } catch (Exception ignore) {}
                }
            }
        }
        if (currentUserId != null) {
            openUserEditor(currentUserId);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Unable to locate current user.");
        }
    }

