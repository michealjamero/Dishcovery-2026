    private void updateFollowerCount() {
        int userId = config.Session.getInstance().getId();
        if (userId <= 0) return;
        
        double count = con.getSingleValue("SELECT COUNT(*) FROM Followers WHERE f_following_id = ?", userId);
        Followers.setText(String.valueOf((int)count));
        
        double followingCount = con.getSingleValue("SELECT COUNT(*) FROM Followers WHERE f_follower_id = ?", userId);
        folowing.setText(String.valueOf((int)followingCount));
    }

    private void displayRecipes() {
        String username = config.Session.getInstance().getUsername();
        if (username == null) return;

        con.ensureRatingsTable();
        String sql =
                "SELECT r.r_id AS ID, " +
                "       r.r_title AS Title, " +
                "       r.r_category AS Category, " +
                "       r.r_status AS Status, " +
                "       IFNULL(ROUND(AVG(rt.r_rating), 1), 0) AS Rating " +
                "FROM Recipes r " +
                "LEFT JOIN Ratings rt ON rt.r_recipe_id = r.r_id " +
                "WHERE r.r_author = ? AND r.r_status = 'Approve' " +
                "GROUP BY r.r_id, r.r_title, r.r_category, r.r_status " +
                "ORDER BY r.r_id DESC";
        con.displayData(sql, sharedRecipeOFUser, username);
    }

